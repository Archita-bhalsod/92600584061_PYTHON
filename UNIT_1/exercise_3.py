'''write a program to perform arithmetic relational and logical operations using python operations.'''
a=10
b=5

#Arithmetic Operation
print("\n------ARITHMETIC OPERATIONS------\n")
print("Addition is: ",a+b)
print("Subtraction is: ",a-b)
print("Multiplication is: ",a*b)
print("Division is: ",a/b)
print("Modular is: ",a%b)

#Relational Operation
print("\n------RELATIONAL OPERATIONS------\n")
print(f"a > b  :" ,a > b)
print(f"a < b  :" ,a < b)
print(f"a == b :" ,a == b)
print(f"a != b :" ,a != b)
print(f"a >= b :" ,a >= b)
print(f"a <= b :" ,a <= b)

#logical operation
print("\n------LOGICAL OPERATIONS------\n")
print("a and b: ",a==10 and b==5)
print("a or b: ",a==10 or b==4)
print("not a: ",not a>b)
print("not b: ",not b<a)
